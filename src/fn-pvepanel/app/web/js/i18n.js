  var current = "zh";

  function setLang(lang) {
    current = STRINGS[lang] ? lang : "zh";
    try { document.documentElement.setAttribute("lang", current === "zh" ? "zh-CN" : "en"); } catch (e) {}
  }

  function getLang() { return current; }

  /* {name} interpolation. Unknown placeholders are left verbatim rather than
     replaced with "undefined" - a missing key should be visible, not silent. */
  function t(key, vars) {
    var table = STRINGS[current] || STRINGS.zh;
    var s = table[key];
    if (s === undefined) s = (STRINGS.zh[key] !== undefined ? STRINGS.zh[key] : key);
    if (vars) {
      s = s.replace(/\{(\w+)\}/g, function (m, name) {
        return vars[name] === undefined ? m : String(vars[name]);
      });
    }
    return s;
  }

  window.I18N = { t: t, setLang: setLang, getLang: getLang, STRINGS: STRINGS };
